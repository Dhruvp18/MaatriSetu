import type { Database } from '@core/db/database.types'
import { internal } from '@core/errors/app-error'

import type {
  BirthPlan,
  ObstetricHistoryEntry,
  Pregnancy,
  PregnancyDating,
} from './pregnancy.types'

/**
 * Pregnancy rows, and how they become domain objects.
 *
 * Separated from the repository so it can be tested without a database. The
 * decision that earns this file is `toDating`: the two anchor columns rise and
 * fall together, and collapsing a half-present anchor into a gestational age
 * would put a fabricated number on the cockpit badge.
 *
 * Row shapes come from `database.types.ts`, generated by `pnpm db:types`.
 */

type Tables = Database['public']['Tables']

/** `pregnancies` — see supabase/migrations/0004_pregnancies.sql. */
export type PregnancyRow = Tables['pregnancies']['Row']

/** `obstetric_history` — prior pregnancies, wherever they happened. */
export type ObstetricHistoryRow = Tables['obstetric_history']['Row']

