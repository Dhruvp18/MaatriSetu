const DURATION_UNITS: readonly DurationUnit[] = ['DAYS', 'WEEKS', 'MONTHS', 'YEARS']

/**
 * The stored complaint list, read defensively: it is jsonb, so an entry
 * without a complaint is dropped and a malformed duration reads as absent
 * rather than as a number nobody wrote.
 */
export function toChiefComplaints(value: unknown): ChiefComplaint[] {
  if (!Array.isArray(value)) return []
  return value.flatMap((item): ChiefComplaint[] => {
    if (typeof item !== 'object' || item === null) return []
    const entry = item as Record<string, unknown>
    const complaint = typeof entry.complaint === 'string' ? entry.complaint.trim() : ''
    if (!complaint) return []
    const n = entry.durationValue
    const unit = entry.durationUnit
    const durationValue = typeof n === 'number' && Number.isFinite(n) && n > 0 ? n : null
    const durationUnit =
      durationValue !== null && typeof unit === 'string' && (DURATION_UNITS as readonly string[]).includes(unit)
        ? (unit as DurationUnit)
        : null
    return [{ complaint, durationValue: durationUnit ? durationValue : null, durationUnit }]
  })
}

/**
 * Visit rows, and how they become domain objects.
 *
 * Separated from the repository so it can be tested without a database. The
 * decision that earns this file is the blood-pressure pairing: two nullable
 * columns become one nullable object, so a lone diastolic — which is not a
 * blood pressure — cannot reach a renderer.
 *
 * Row shapes come from `database.types.ts`, generated by `pnpm db:types`.
 */

type Tables = Database['public']['Tables']

/** `visits` — see supabase/migrations/0005_visits.sql. */
export type VisitRow = Tables['visits']['Row']

/** `visit_vitals` — one row per reading, never one row per visit. */
export type VisitVitalsRow = Tables['visit_vitals']['Row']

/** `visit_advice` — at most one row per visit, written by the atomic save. */
export type VisitAdviceRow = Tables['visit_advice']['Row']

/** `doctor_references` — see supabase/migrations/0024_cockpit_clinical_history.sql. */
export type DoctorReferenceRow = Tables['doctor_references']['Row']

